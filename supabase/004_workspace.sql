-- ---------------------------------------------------------------------------
-- SQLite date/time functions (used by the apps' SQL via api/_workspace/pg.py)
-- 'localtime' means India time.
-- ---------------------------------------------------------------------------
create or replace function wscompat.sq_ts(v text, mods text[]) returns timestamp
language plpgsql stable as $$
declare t timestamp; m text; n int;
begin
  if v is null then return null; end if;
  if lower(v) = 'now' then
    t := now() at time zone 'UTC';
  else
    begin
      t := replace(replace(trim(v), 'T', ' '), 'Z', '')::timestamp;
    exception when others then return null;
    end;
  end if;
  foreach m in array coalesce(mods, '{}'::text[]) loop
    m := lower(trim(m));
    if m = 'localtime' then t := (t at time zone 'UTC') at time zone 'Asia/Kolkata';
    elsif m = 'utc' then t := (t at time zone 'Asia/Kolkata') at time zone 'UTC';
    elsif m = 'start of month' then t := date_trunc('month', t);
    elsif m = 'start of year' then t := date_trunc('year', t);
    elsif m = 'start of day' then t := date_trunc('day', t);
    elsif m like 'weekday %' then
      n := split_part(m, ' ', 2)::int;            -- 0 = Sunday; move forward to that weekday (or stay)
      t := t + (((n - extract(dow from t)::int) + 7) % 7) * interval '1 day';
    elsif m ~ '^[+-]?[0-9]+(\.[0-9]+)? *(second|minute|hour|day|month|year)s?$' then
      t := t + m::interval;
    end if;
  end loop;
  return t;
end $$;

create or replace function wscompat.sq_date(v text, variadic mods text[] default '{}') returns text
language sql stable as $$ select to_char(wscompat.sq_ts(v, mods), 'YYYY-MM-DD') $$;

create or replace function wscompat.sq_datetime(v text, variadic mods text[] default '{}') returns text
language sql stable as $$ select to_char(wscompat.sq_ts(v, mods), 'YYYY-MM-DD HH24:MI:SS') $$;

create or replace function wscompat.sq_julianday(v text, variadic mods text[] default '{}') returns double precision
language sql stable as $$ select extract(epoch from wscompat.sq_ts(v, mods))::double precision / 86400.0 + 2440587.5 $$;

create or replace function wscompat.sq_strftime(fmt text, v text, variadic mods text[] default '{}') returns text
language plpgsql stable as $$
declare t timestamp := wscompat.sq_ts(v, mods); out text := ''; i int := 1; c text;
begin
  if t is null or fmt is null then return null; end if;
  while i <= length(fmt) loop
    c := substr(fmt, i, 1);
    if c = '%' and i < length(fmt) then
      i := i + 1; c := substr(fmt, i, 1);
      out := out || case c
        when 'Y' then to_char(t, 'YYYY') when 'm' then to_char(t, 'MM') when 'd' then to_char(t, 'DD')
        when 'H' then to_char(t, 'HH24') when 'M' then to_char(t, 'MI') when 'S' then to_char(t, 'SS')
        when 'j' then to_char(t, 'DDD') when 'w' then extract(dow from t)::int::text
        when 'W' then lpad(((extract(doy from t)::int - 1 + 7 - ((extract(dow from t)::int + 6) % 7)) / 7)::text, 2, '0')
        when '%' then '%' else '%' || c end;
    else
      out := out || c;
    end if;
    i := i + 1;
  end loop;
  return out;
end $$;

-- SQLite's ROUND works on floats; Postgres only rounds numerics to n places.
create or replace function wscompat.round(x double precision, n integer) returns double precision
language sql immutable as $$ select round(x::numeric, n)::double precision $$;

create or replace function wscompat.utc_now() returns text
language sql stable as $$ select to_char(now() at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"') $$;

