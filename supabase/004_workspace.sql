-- Defence in depth: RLS on, no policies, so even if a schema were exposed nothing is readable through the API.
do $$
declare r record;
begin
  for r in select schemaname, tablename from pg_tables where schemaname in ('workdesk', 'expenseflow') loop
    execute format('alter table %I.%I enable row level security', r.schemaname, r.tablename);
  end loop;
end $$;

