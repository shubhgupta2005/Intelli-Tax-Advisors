# ── Leave requests & balances ───────────────────────────────────────────────

LEAVE_TYPES = {"CL": "Casual leave", "SL": "Sick leave", "EL": "Earned leave", "LOP": "Unpaid leave (LOP)"}
LEAVE_QUOTA_DEFAULT = {"CL": 12, "SL": 12, "EL": 15}      # days per calendar year; editable in Settings


def leave_quotas():
    return {t: num(setting(f"leave_quota_{t}", str(q)), q) for t, q in LEAVE_QUOTA_DEFAULT.items()}


def working_days(frm, to):
    """Mon–Fri days in the range that aren't office holidays (the same weekend rule as attendance)."""
    hol = holiday_map(frm, to)
    d, last, out = datetime.strptime(frm, "%Y-%m-%d").date(), datetime.strptime(to, "%Y-%m-%d").date(), []
    while d <= last:
        if d.weekday() < 5 and d.isoformat() not in hol:
            out.append(d.isoformat())
        d += timedelta(days=1)
    return out


def leave_balances(eid, year=None):
    year = str(year or date.today().year)
    used = {t: 0.0 for t in LEAVE_TYPES}
    for r in rows("SELECT leave_type, days FROM leave_requests WHERE employee_id=? AND status='approved' AND substr(from_day,1,4)=?",
                  (eid, year)):
        used[r["leave_type"]] = used.get(r["leave_type"], 0) + r["days"]
    pending = {t: 0.0 for t in LEAVE_TYPES}
    for r in rows("SELECT leave_type, days FROM leave_requests WHERE employee_id=? AND status='pending' AND substr(from_day,1,4)=?",
                  (eid, year)):
        pending[r["leave_type"]] = pending.get(r["leave_type"], 0) + r["days"]
    q = leave_quotas()
    return [{"type": t, "label": LEAVE_TYPES[t], "quota": q.get(t), "used": used[t], "pending": pending[t],
             "left": round(q[t] - used[t], 1) if t in q else None} for t in LEAVE_TYPES]


LEAVE_SELECT = """SELECT r.*, e.name employee_name, e.color employee_color, d.name decided_by_name FROM leave_requests r
    JOIN employees e ON e.id=r.employee_id LEFT JOIN employees d ON d.id=r.decided_by"""


def apply_leave(r):
    """Put an approved request on the attendance calendar."""
    for day in (working_days(r["from_day"], r["to_day"]) if r["kind"] == "full" else [r["from_day"]]):
        get_db().execute("""INSERT OR REPLACE INTO leaves(employee_id, day, kind, note, created_by, leave_type, request_id)
            VALUES (?,?,?,?,?,?,?)""", (r["employee_id"], day, r["kind"], r["reason"], g.uid, r["leave_type"], r["id"]))


def leave_label(r):
    rng = r["from_day"] if r["from_day"] == r["to_day"] else f"{r['from_day']} to {r['to_day']}"
    return f"{LEAVE_TYPES.get(r['leave_type'], 'leave').lower()}{' (half day)' if r['kind'] == 'half' else ''} on {rng}"


