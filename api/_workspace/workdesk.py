def remind_expiring_documents():
    """Daily (cron): tell managers about documents expiring in 30 days, 7 days, today, or already expired."""
    for d in expiring_documents(30):
        left = (datetime.strptime(d["expires_on"], "%Y-%m-%d").date() - date.today()).days
        stage = "expired" if left < 0 else "today" if left == 0 else "7" if left <= 7 else "30"
        if scalar("SELECT reminded FROM client_documents WHERE id=?", (d["id"],)) == stage:
            continue
        when = "has expired" if left < 0 else "expires today" if left == 0 else f"expires in {left} days"
        notify_managers("document", f"{d['client_name']}: {d['title']} ({d['category']}) {when}", url=f"/#/clients/{d['client_id']}")
        get_db().execute("UPDATE client_documents SET reminded=? WHERE id=?", (stage, d["id"]))
    get_db().commit()


