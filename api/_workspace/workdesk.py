    get_db().execute("UPDATE time_logs SET ended_at=?, minutes=?, note=COALESCE(?,note) WHERE id=?",
                     (end, mins, note or None, r["id"]))
    log("timer", f"stopped work on “{r['title']}” ({mins // 60}h {mins % 60}m)", r["task_id"], r["client_id"])
    get_db().commit()
    touch()
    return mins


