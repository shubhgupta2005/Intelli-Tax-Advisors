@app.post("/api/leave-requests")
@login_required
def create_leave_request():
    d = body()
    frm, to = d.get("from_day") or "", d.get("to_day") or d.get("from_day") or ""
    kind = "half" if d.get("kind") == "half" else "full"
    ltype = d.get("leave_type") if d.get("leave_type") in LEAVE_TYPES else "CL"
    if not (re.fullmatch(r"\d{4}-\d{2}-\d{2}", frm) and re.fullmatch(r"\d{4}-\d{2}-\d{2}", to)) or to < frm:
        return bad("Choose the leave dates (the end can't be before the start)")
    if frm[:4] != to[:4]:
        return bad("Please split leave that crosses into a new year into two requests")
    if kind == "half":
        to = frm
    days = 0.5 if kind == "half" else float(len(working_days(frm, to)))
    if kind == "half" and not working_days(frm, frm):
        days = 0
    if not days:
        return bad("Those dates are weekends or holidays — no leave needed")
    if scalar("""SELECT 1 FROM leave_requests WHERE employee_id=? AND status IN ('pending','approved')
                 AND from_day<=? AND to_day>=?""", (g.uid, to, frm)):
        return bad("You already have leave requested for some of these days")
    bal = next(b for b in leave_balances(g.uid, frm[:4]) if b["type"] == ltype)
    if bal["left"] is not None and days > bal["left"] - bal["pending"]:
        return bad(f"Only {max(bal['left'] - bal['pending'], 0):g} day(s) of {bal['label'].lower()} left — choose another type or Unpaid (LOP)")
    auto = is_manager()               # managers and admins record their own leave directly
    rid = execute("""INSERT INTO leave_requests(employee_id, from_day, to_day, kind, leave_type, days, reason, status, decided_by, decided_at)
                     VALUES (?,?,?,?,?,?,?,?,?,?)""", (g.uid, frm, to, kind, ltype, days, (d.get("reason") or "").strip()[:500] or None,
                                                     "approved" if auto else "pending", g.uid if auto else None, utcnow() if auto else None))
    r = one("SELECT * FROM leave_requests WHERE id=?", (rid,))
    if auto:
        apply_leave(r)
        log("attendance", f"took {leave_label(r)}")
    else:
        notify_managers("leave", f"asked for {leave_label(r)}" + (f" — {r['reason']}" if r["reason"] else ""), url="/#/attendance/leave")
        log("attendance", f"requested {leave_label(r)}")
    get_db().commit()
    touch()
    return jsonify(ok=True, id=rid, status=r["status"]), 201


